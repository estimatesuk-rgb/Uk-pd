import {strict as assert} from 'node:assert';
import {readFileSync} from 'node:fs';
import {chaseIsDue,nextChaseDate,CHASE_ROUNDS,officeChaseBody,officeChaseSubject,clientChaseBody} from '../src/chase-policy.mjs';
const start='2026-10-01T09:00:00.000Z';
assert.equal(CHASE_ROUNDS,3);
assert.equal(nextChaseDate(start,0).toISOString(),'2026-10-08T09:00:00.000Z');
assert.equal(nextChaseDate(start,1).toISOString(),'2026-10-15T09:00:00.000Z');
assert.equal(nextChaseDate(start,2).toISOString(),'2026-10-22T09:00:00.000Z');
assert.equal(nextChaseDate(start,3),null);
assert.equal(chaseIsDue(start,0,'2026-10-08T08:59:59.000Z'),false);
assert.equal(chaseIsDue(start,0,'2026-10-08T09:00:00.000Z'),true);
assert.equal(chaseIsDue(start,1,'2026-10-14T10:00:00.000Z'),false);
assert.equal(chaseIsDue(start,1,'2026-10-15T09:00:00.000Z'),true);
assert.equal(chaseIsDue(start,3,'2026-12-01T09:00:00.000Z'),false);
assert.equal(chaseIsDue('invalid',0,new Date()),false);
assert.equal(nextChaseDate('2026-10-01 09:00:00',2).toISOString(),'2026-10-22T09:00:00.000Z');
